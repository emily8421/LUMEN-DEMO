@runtime_checkable
class SearchRepository(Protocol):
    """检索域：RAG 召回 / 全文检索 / 全量分块与全量文档（INTERNAL 内部路径为主）。"""

    def list_all_document_chunks(self) -> list[DocumentChunk]: ...

    # INTERNAL（CQ-P1-004）：无权限 scope 的全量方法，仅系统内部路径（启动回填等）使用；
