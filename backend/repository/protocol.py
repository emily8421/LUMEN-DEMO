@runtime_checkable
class DocumentRepository(Protocol):
    """文档与内容域：文档 CRUD / 版本 / 双链（doc + chunk 存储面 + doc_link）。"""

    def create_document(self, space_id: int, title: str, content_md: str, owner_id: int, permission: DocumentPermission, folder_id: int | None = None) -> Document: ...

    def delete_document(self, document_id: int) -> None: ...

    def find_document_id_by_title(self, space_id: int, title: str) -> int | None: ...

    def get_document(self, document_id: int) -> Document | None: ...

    def get_document_version(self, document_id: int, version_no: int) -> DocumentVersion | None: ...

    def list_doc_links(self, space_id: int, document_id: int, direction: str) -> list[DocLink]: ...

    def list_document_chunks(self, document_id: int) -> list[DocumentChunk]: ...

    def list_document_versions(self, document_id: int) -> list[DocumentVersion]: ...

    def list_visible_documents(self, user_id: int, space_id: int) -> list[Document]: ...

    def replace_document_chunks(self, document_id: int, chunk_texts: list[str]) -> list[DocumentChunk]: ...

    def replace_document_wikilinks(self, space_id: int, source_document_id: int, drafts: list[DocLinkDraft]) -> list[DocLink]: ...

    def require_document(self, document_id: int) -> Document: ...

    def restore_document_version(self, document_id: int, version_no: int, editor_id: int) -> Document: ...

    def update_document(self, document_id: int, title: str, content_md: str, permission: DocumentPermission, editor_id: int) -> Document: ...

    def upsert_manual_link(self, space_id: int, source_document_id: int, target_document_id: int | None, target_title: str, link_text: str) -> DocLink: ...

